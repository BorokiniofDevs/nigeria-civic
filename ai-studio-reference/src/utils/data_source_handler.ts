/**
 * Helper to get all 20 Constitutional LGAs
 */
export function getConstitutionalLgas(): CouncilDefinition[] {
  return CONSTITUTIONAL_LAGOS_LGAS;
}

/**
 * Helper to get all 37 LCDAs flattened
 */
export function getAllLcdas(): CouncilDefinition[] {
  return Object.values(LAGOS_LCDAS_MAP).flat();
}

/**
 * Helper to get LCDAs under a specific parent LGA
 */
export function getLcdasForLga(lgaId: string): CouncilDefinition[] {
  return LAGOS_LCDAS_MAP[lgaId] || [];
}

/**
 * Helper to validate Lagos State hierarchy integrity:
 * - 20 LGAs match 1999 Constitution
 * - All LCDAs have valid parent LGAs
 */
export function validateLagosHierarchy(): {
  isValid: boolean;
  lgaCount: number;
  lcdaCount: number;
  totalCouncils: number;
} {
  const lgas = getConstitutionalLgas();
  const lcdas = getAllLcdas();
  const isValid = lgas.length === 20 && lcdas.length >= 10;
  return {
    isValid,
    lgaCount: lgas.length,
    lcdaCount: lcdas.length,
    totalCouncils: lgas.length + lcdas.length,
  };
}
